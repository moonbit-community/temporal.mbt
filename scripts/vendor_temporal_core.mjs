#!/usr/bin/env node
/* eslint-env node */

import childProcess from "node:child_process";
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, "..");
const sourceRoot = path.join(repoRoot, "temporal-sdk");
const vendorRoot = path.join(repoRoot, "vendor", "temporal-sdk-core");
const vendorStamp = "VENDOR.stamp";

const workspaceMembers = [
  "crates/common",
  "crates/client",
  "crates/sdk-core",
  "crates/macros",
  "crates/sdk-core-c-bridge",
];

const rootFiles = [
  ".cargo",
  ".clippy.toml",
  "Cargo.toml",
  "LICENSE.txt",
  "rustfmt.toml",
];

function run(cmd, args, options = {}) {
  childProcess.execFileSync(cmd, args, {
    cwd: options.cwd || repoRoot,
    env: { ...process.env, ...(options.env || {}) },
    stdio: options.stdio || "inherit",
  });
}

function copyRecursive(src, dst) {
  const stat = fs.lstatSync(src);
  if (stat.isSymbolicLink()) {
    fs.symlinkSync(fs.readlinkSync(src), dst);
    return;
  }
  if (stat.isDirectory()) {
    fs.mkdirSync(dst, { recursive: true });
    for (const entry of fs.readdirSync(src)) {
      if (entry === ".git" || entry === "target") {
        continue;
      }
      copyRecursive(path.join(src, entry), path.join(dst, entry));
    }
    return;
  }
  fs.mkdirSync(path.dirname(dst), { recursive: true });
  fs.copyFileSync(src, dst);
}

function replaceInFile(file, edit) {
  const before = fs.readFileSync(file, "utf8");
  const after = edit(before);
  if (before !== after) {
    fs.writeFileSync(file, after);
  }
}

function hashFile(relativePath) {
  const hash = crypto.createHash("sha256");
  hash.update(fs.readFileSync(path.join(vendorRoot, relativePath)));
  return hash.digest("hex");
}

function vendorStampContent(commit) {
  const stampInputs = [
    "Cargo.lock",
    "Cargo.toml",
    "crates/common/Cargo.toml",
    "crates/common/build.rs",
    "crates/common/generated/descriptors.bin",
    "crates/sdk-core/Cargo.toml",
    "crates/sdk-core-c-bridge/Cargo.toml",
    "crates/sdk-core-c-bridge/build.rs",
    "crates/sdk-core-c-bridge/include/temporal-sdk-core-c-bridge.h",
  ];
  return [
    "# Generated by scripts/vendor_temporal_core.mjs",
    `commit=${commit}`,
    ...stampInputs.map(file => `${file}=sha256:${hashFile(file)}`),
    "",
  ].join("\n");
}

function writeVendorStamp(commit) {
  fs.writeFileSync(path.join(vendorRoot, vendorStamp), vendorStampContent(commit));
}

function patchWorkspaceManifest() {
  const file = path.join(vendorRoot, "Cargo.toml");
  replaceInFile(file, text =>
    text.replace(
      /members = \[[\s\S]*?\]/,
      `members = [\n${workspaceMembers.map(member => `    "${member}",`).join("\n")}\n]`,
    ),
  );
}

function patchBridgeCrate() {
  replaceInFile(path.join(vendorRoot, "crates/sdk-core-c-bridge/Cargo.toml"), text =>
    text
      .replace('crate-type = ["cdylib"]', 'crate-type = ["staticlib"]')
      .replace(/\n\[build-dependencies\]\ncbindgen[^\n]*\n/, "\n"),
  );

  fs.writeFileSync(
    path.join(vendorRoot, "crates/sdk-core-c-bridge/build.rs"),
    `fn main() {\n    println!("cargo:rerun-if-changed=include/temporal-sdk-core-c-bridge.h");\n}\n`,
  );
}

function patchSdkCoreCrate() {
  replaceInFile(path.join(vendorRoot, "crates/sdk-core/Cargo.toml"), text =>
    text
      .replace(/^temporalio-sdk = \{ path = "\.\.\/sdk" \}\n/m, "")
      .replace(/^lru = "0\.18"$/m, 'lru = "0.16"'),
  );
}

function patchCommonCrate() {
  replaceInFile(path.join(vendorRoot, "crates/common/Cargo.toml"), text =>
    text.replace(/^ringbuf = \{ version = "0\.5", optional = true \}$/m, 'ringbuf = { version = "0.4", optional = true }'),
  );
}

function patchCommonBuild() {
  const file = path.join(vendorRoot, "crates/common/build.rs");
  replaceInFile(file, text => {
    let patched = text.replace(
      "    fs::File,\n",
      "    fs::{self, File},\n",
    );
    patched = patched.replace(
      "    let descriptor_file = out.join(\"descriptors.bin\");\n",
      `    let descriptor_file = out.join("descriptors.bin");\n    let generated_descriptor_file = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap())\n        .join("generated")\n        .join("descriptors.bin");\n    let use_generated_descriptors = env::var("TEMPORAL_MBT_VENDOR_GENERATE_DESCRIPTORS")\n        .map(|v| v != "1")\n        .unwrap_or(true);\n    if use_generated_descriptors {\n        fs::copy(&generated_descriptor_file, &descriptor_file).map_err(|err| {\n            format!(\n                "failed to copy vendored descriptor set from {}: {err}",\n                generated_descriptor_file.display()\n            )\n        })?;\n    }\n`,
    );
    patched = patched.replace(
      "    builder\n        .field_attribute(\n",
      "    builder = builder\n        .field_attribute(\n",
    );
    patched = patched.replace(
      "        .file_descriptor_set_path(&descriptor_file)\n        .skip_debug([\"temporal.api.common.v1.Payload\"])\n",
      `        .file_descriptor_set_path(&descriptor_file);\n\n    if use_generated_descriptors {\n        builder = builder.skip_protoc_run();\n    }\n\n    builder\n        .skip_debug(["temporal.api.common.v1.Payload"])\n`,
    );
    return patched;
  });
}

function readGitDir(worktree) {
  const dotGit = path.join(worktree, ".git");
  const stat = fs.lstatSync(dotGit);
  if (stat.isDirectory()) {
    return dotGit;
  }
  const text = fs.readFileSync(dotGit, "utf8").trim();
  const match = /^gitdir:\s*(.+)$/.exec(text);
  if (!match) {
    throw new Error(`cannot parse ${dotGit}`);
  }
  return path.resolve(worktree, match[1]);
}

function gitCommit(worktree) {
  const gitDir = readGitDir(worktree);
  const head = fs.readFileSync(path.join(gitDir, "HEAD"), "utf8").trim();
  if (!head.startsWith("ref: ")) {
    return head;
  }
  const ref = head.slice("ref: ".length);
  const refPath = path.join(gitDir, ref);
  if (fs.existsSync(refPath)) {
    return fs.readFileSync(refPath, "utf8").trim();
  }
  const packedRefs = path.join(gitDir, "packed-refs");
  if (fs.existsSync(packedRefs)) {
    for (const line of fs.readFileSync(packedRefs, "utf8").split(/\r?\n/)) {
      if (line.startsWith("#") || line.startsWith("^") || line.trim() === "") {
        continue;
      }
      const [sha, name] = line.split(" ");
      if (name === ref) {
        return sha;
      }
    }
  }
  throw new Error(`cannot resolve ${ref} in ${gitDir}`);
}

function writeVendorMetadata(commit) {
  const metadata = {
    source: "https://github.com/temporalio/sdk-rust",
    submodule: "temporal-sdk",
    commit,
    generatedAt: new Date().toISOString(),
    packages: workspaceMembers,
    notes: [
      "sdk-core-c-bridge is patched to build as a staticlib.",
      "sdk-core-c-bridge build.rs is patched to avoid cbindgen during normal builds.",
      "common/build.rs is patched to use generated/descriptors.bin unless TEMPORAL_MBT_VENDOR_GENERATE_DESCRIPTORS=1.",
      "rust-toolchain.toml is intentionally omitted so normal builds use the caller's installed Rust toolchain.",
      "lru and ringbuf are pinned to locally cached compatible versions for offline builds in this repository.",
    ],
  };
  fs.writeFileSync(
    path.join(vendorRoot, "VENDOR.json"),
    `${JSON.stringify(metadata, null, 2)}\n`,
  );
}

function findNewestDescriptor() {
  const buildRoot = path.join(vendorRoot, "target");
  let newest = null;
  let newestMtime = 0;
  function walk(dir) {
    if (!fs.existsSync(dir)) return;
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        walk(full);
      } else if (entry.isFile() && entry.name === "descriptors.bin") {
        const mtime = fs.statSync(full).mtimeMs;
        if (mtime > newestMtime) {
          newest = full;
          newestMtime = mtime;
        }
      }
    }
  }
  walk(buildRoot);
  if (!newest) {
    throw new Error("Cargo build did not produce descriptors.bin");
  }
  return newest;
}

function generateDescriptorAndLock() {
  fs.mkdirSync(path.join(vendorRoot, "crates/common/generated"), { recursive: true });
  run("cargo", ["generate-lockfile", "--offline"], { cwd: vendorRoot });
  run("cargo", ["build", "-p", "temporalio-common", "--offline"], {
    cwd: vendorRoot,
    env: { TEMPORAL_MBT_VENDOR_GENERATE_DESCRIPTORS: "1" },
  });
  fs.copyFileSync(
    findNewestDescriptor(),
    path.join(vendorRoot, "crates/common/generated/descriptors.bin"),
  );
}

function refresh() {
  if (!fs.existsSync(sourceRoot)) {
    throw new Error("temporal-sdk submodule is missing");
  }
  const commit = gitCommit(sourceRoot);
  fs.rmSync(vendorRoot, { recursive: true, force: true });
  fs.mkdirSync(vendorRoot, { recursive: true });
  for (const file of rootFiles) {
    const src = path.join(sourceRoot, file);
    if (fs.existsSync(src)) {
      copyRecursive(src, path.join(vendorRoot, file));
    }
  }
  for (const member of workspaceMembers) {
    copyRecursive(path.join(sourceRoot, member), path.join(vendorRoot, member));
  }
  patchWorkspaceManifest();
  patchCommonCrate();
  patchSdkCoreCrate();
  patchBridgeCrate();
  patchCommonBuild();
  generateDescriptorAndLock();
  writeVendorMetadata(commit);
  writeVendorStamp(commit);
  console.log(`vendored temporal-sdk ${commit} into ${path.relative(repoRoot, vendorRoot)}`);
}

function check() {
  const metadataFile = path.join(vendorRoot, "VENDOR.json");
  if (!fs.existsSync(metadataFile)) {
    throw new Error("vendor/temporal-sdk-core/VENDOR.json is missing");
  }
  const metadata = JSON.parse(fs.readFileSync(metadataFile, "utf8"));
  const commit = gitCommit(sourceRoot);
  if (metadata.commit !== commit) {
    throw new Error(`vendor commit ${metadata.commit} does not match submodule ${commit}`);
  }
  const required = [
    "Cargo.toml",
    "Cargo.lock",
    vendorStamp,
    "crates/common/generated/descriptors.bin",
    "crates/sdk-core-c-bridge/include/temporal-sdk-core-c-bridge.h",
  ];
  for (const file of required) {
    if (!fs.existsSync(path.join(vendorRoot, file))) {
      throw new Error(`vendor snapshot is missing ${file}`);
    }
  }
  const expectedStamp = vendorStampContent(commit);
  const actualStamp = fs.readFileSync(path.join(vendorRoot, vendorStamp), "utf8");
  if (actualStamp !== expectedStamp) {
    throw new Error(`vendor snapshot stamp is stale; run ${path.relative(repoRoot, process.argv[1])}`);
  }
  console.log(`vendor snapshot matches temporal-sdk ${commit}`);
}

const args = new Set(process.argv.slice(2));
try {
  if (args.has("--check")) {
    check();
  } else {
    refresh();
  }
} catch (err) {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
}
